begin;

create table if not exists public.biteboss_crew_activity_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  organization_id uuid,
  organization_name text not null default '',
  event_type text not null check (event_type in (
    'crew_joined','crew_left','crew_kicked','crew_disbanded','crew_leader_changed'
  )),
  actor_user_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists biteboss_crew_activity_events_user_created_idx
  on public.biteboss_crew_activity_events(user_id, created_at desc);

alter table public.biteboss_crew_activity_events enable row level security;
revoke all on public.biteboss_crew_activity_events from anon, authenticated;

create or replace function public.biteboss_kick_organization_member_v7513(
  p_target_user_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := public.biteboss_player_user_id();
  v_org_id uuid;
  v_org_name text := '';
  v_target_role text;
  v_member_name text := '';
begin
  if not public.biteboss_player_authenticated() or v_uid is null then
    return jsonb_build_object('ok', false, 'error', 'MEMBER_LOGIN_REQUIRED');
  end if;

  if p_target_user_id is null then
    return jsonb_build_object('ok', false, 'error', 'TARGET_REQUIRED');
  end if;

  if p_target_user_id = v_uid then
    return jsonb_build_object('ok', false, 'error', 'CANNOT_KICK_SELF');
  end if;

  select om.organization_id, coalesce(o.name,'')
    into v_org_id, v_org_name
  from public.biteboss_organization_members om
  join public.biteboss_organizations o on o.id = om.organization_id
  where om.user_id = v_uid
    and om.role = 'leader'
  limit 1;

  if v_org_id is null then
    return jsonb_build_object('ok', false, 'error', 'LEADER_REQUIRED');
  end if;

  select om.role
    into v_target_role
  from public.biteboss_organization_members om
  where om.organization_id = v_org_id
    and om.user_id = p_target_user_id
  limit 1
  for update;

  if v_target_role is null then
    return jsonb_build_object('ok', false, 'error', 'TARGET_NOT_MEMBER');
  end if;

  if v_target_role = 'leader' then
    return jsonb_build_object('ok', false, 'error', 'CANNOT_KICK_LEADER');
  end if;

  select coalesce(
    nullif(trim(p.nickname),''),
    nullif(trim(a.username),''),
    '크루원'
  )
  into v_member_name
  from (select p_target_user_id as user_id) u
  left join public.biteboss_profiles p on p.user_id = u.user_id
  left join public.biteboss_member_accounts a on a.owner_user_id = u.user_id
  limit 1;

  delete from public.biteboss_organization_members
  where organization_id = v_org_id
    and user_id = p_target_user_id;

  insert into public.biteboss_crew_activity_events(
    user_id, organization_id, organization_name, event_type, actor_user_id, created_at
  ) values (
    p_target_user_id, v_org_id, v_org_name, 'crew_kicked', v_uid, now()
  );

  return jsonb_build_object(
    'ok', true,
    'organization_id', v_org_id,
    'organization_name', v_org_name,
    'target_user_id', p_target_user_id,
    'member_name', coalesce(v_member_name,'크루원')
  );
end;
$$;

grant execute on function public.biteboss_kick_organization_member_v7513(uuid) to authenticated;

create or replace function public.biteboss_player_profile_v7568(
  p_user_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_base jsonb;
  v_target uuid;
  v_recent jsonb := '[]'::jsonb;
begin
  v_base := public.biteboss_player_profile(p_user_id);

  if coalesce((v_base->>'ok')::boolean,false) is not true then
    return v_base;
  end if;

  v_target := coalesce(
    p_user_id,
    nullif(v_base #>> '{player,user_id}','')::uuid,
    public.biteboss_player_user_id()
  );

  select coalesce(
    jsonb_agg(q.item order by (q.item->>'created_at')::timestamptz desc),
    '[]'::jsonb
  )
  into v_recent
  from (
    select item
    from (
      select value as item
      from jsonb_array_elements(coalesce(v_base->'recent_activity','[]'::jsonb))

      union all

      select jsonb_build_object(
        'id', 'crew-event-' || e.id::text,
        'created_at', e.created_at,
        'store_id', null,
        'store_name', e.organization_name,
        'organization_name', e.organization_name,
        'result', e.event_type,
        'method', 'crew_event',
        'activity_type', 'crew',
        'as_challenger', true
      )
      from public.biteboss_crew_activity_events e
      where e.user_id = v_target
    ) merged
    where nullif(item->>'created_at','') is not null
    order by (item->>'created_at')::timestamptz desc
    limit 20
  ) q;

  return jsonb_set(v_base, '{recent_activity}', v_recent, true);
end;
$$;

